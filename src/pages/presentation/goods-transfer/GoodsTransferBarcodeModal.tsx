import React, { useEffect, useMemo, useState } from 'react';
import { useQuery } from '@tanstack/react-query';
import Modal, {
	ModalBody,
	ModalFooter,
	ModalHeader,
	ModalTitle,
} from '../../../components/bootstrap/Modal';
import FormGroup from '../../../components/bootstrap/forms/FormGroup';
import Select from '../../../components/bootstrap/forms/Select';
import Input from '../../../components/bootstrap/forms/Input';
import Button from '../../../components/bootstrap/Button';
import Alert from '../../../components/bootstrap/Alert';
import Badge from '../../../components/bootstrap/Badge';
import Spinner from '../../../components/bootstrap/Spinner';
import { usePermission } from '../../../hooks/usePermission';
import { getWarehousesApi } from '../../../api/warehouses.api';
import {
	GoodsTransferRequest,
	GoodsTransferAllocationDraws,
	PackingListDraw,
	PackingListOption,
	getPackingListOptionsApi,
} from '../../../api/goodsTransfer.api';
import { code128Svg } from '../../../helpers/code128';

interface Props {
	isOpen: boolean;
	setIsOpen: (v: boolean) => void;
	request: GoodsTransferRequest | null;
	onGenerate: (id: number, warehouseId: number, allocations: GoodsTransferAllocationDraws[]) => void;
	isLoading: boolean;
	/** Pre-selects (and locks) the warehouse when opened from that warehouse's own tab. */
	presetWarehouseId?: number | null;
}

// FIFO fill — the same "first come first go" order the backend used to draw
// automatically, now just the suggested starting point: fills from the
// oldest packing list(s) first until `qtyNeeded` is covered, falling back to
// "no packing list / unknown source" only if the real options run out. The
// keeper sees exactly this in the picker and can edit it before generating.
const defaultDraws = (options: PackingListOption[], qtyNeeded: number): PackingListDraw[] => {
	const rows: PackingListDraw[] = [];
	let remaining = qtyNeeded;
	for (const opt of options) {
		if (remaining <= 0) break;
		const take = Math.min(remaining, opt.remainingQty);
		if (take > 0) {
			rows.push({ batchId: opt.batchId, qty: take });
			remaining -= take;
		}
	}
	if (remaining > 0) {
		rows.push({ batchId: null, qty: remaining });
	}
	return rows;
};

const drawsTotal = (draws: PackingListDraw[]) => draws.reduce((sum, d) => sum + (d.qty || 0), 0);

const escapeHtml = (value: string) =>
	value
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;');

/**
 * Step 3 — "after got the item list he generates bar code for requested
 * items ... if requested items are 20, store keeper generate 20 bar codes
 * and print and tag to the items (need bulk option)". One unique tag per
 * physical unit (not one shared tag per line) — see
 * GoodsTransferService#generateBarcodes / GoodsTransferBarcodeUnit.
 * <p>
 * Since approval can split a line across several warehouses, generating,
 * viewing AND printing are all scoped to ONE warehouse at a time, exactly
 * like Issue — "specific barcodes can be generated by warehouse assigned
 * user... if 100 items request 50 goes to warehouse 1 and 50 goes to
 * warehouse 2, only 50 barcodes can be created by warehouse 1 assigned
 * user" — that same slice-of-50 is also all that warehouse 1's user can
 * ever print here; warehouse 2's own 50 tags are simply never in the sheet.
 * Other warehouses on the same request generate and print their own tags
 * independently via their own call.
 * <p>
 * The print sheet opens in a dedicated new browser tab (so the main app's
 * print CSS is untouched). Each label's barcode is rendered HERE, in the app,
 * as an inline Code 128 SVG (see helpers/code128) before the tab is opened —
 * the sheet used to load JsBarcode from a CDN inside that tab and draw on its
 * `load` event, which left every label blank whenever the script didn't load
 * or the event didn't fire. Now the tab needs no network and no script.
 */
const GoodsTransferBarcodeModal: React.FC<Props> = ({
	isOpen,
	setIsOpen,
	request,
	onGenerate,
	isLoading,
	presetWarehouseId,
}) => {
	const [printing, setPrinting] = useState(false);
	const { canActOnWarehouse, isSuperAdmin, warehouseIds } = usePermission();
	const { data: warehouses = [] } = useQuery({ queryKey: ['warehouses'], queryFn: getWarehousesApi });

	// Every warehouse that has any allocation at all on this request — the
	// full set a user could ever pick to view/generate/print, before
	// narrowing to what they're actually assigned to.
	const allocatedWarehouseIds = useMemo(() => {
		const ids = new Set<number>();
		request?.items.forEach((item) =>
			item.allocations.forEach((a) => {
				if (a.allocatedQty > 0) ids.add(a.warehouseId);
			}),
		);
		return ids;
		// eslint-disable-next-line react-hooks/exhaustive-deps
	}, [request]);

	// The subset of those still missing their own tags — used to prioritise
	// auto-selection and to gate the Generate button.
	const pendingWarehouseIds = useMemo(() => {
		const ids = new Set<number>();
		request?.items.forEach((item) =>
			item.allocations.forEach((a) => {
				if (a.allocatedQty > 0 && a.barcodeUnits.length === 0) ids.add(a.warehouseId);
			}),
		);
		return ids;
		// eslint-disable-next-line react-hooks/exhaustive-deps
	}, [request]);

	// Warehouses this user may act on at all here — generate OR view/print —
	// each one strictly its own slice. A user with no allocation-bearing
	// warehouse assignment (or unrestricted) sees every warehouse on the
	// request; otherwise only their own.
	const selectableWarehouses = useMemo(
		() => warehouses.filter((w) => allocatedWarehouseIds.has(w.id) && canActOnWarehouse(w.id)),
		// eslint-disable-next-line react-hooks/exhaustive-deps
		[warehouses, allocatedWarehouseIds],
	);

	const [warehouseId, setWarehouseId] = useState<number | ''>('');

	useEffect(() => {
		if (!isOpen) {
			setWarehouseId('');
			return;
		}
		if (presetWarehouseId) {
			setWarehouseId(presetWarehouseId);
			return;
		}
		const stillPending = selectableWarehouses.filter((w) => pendingWarehouseIds.has(w.id));
		if (stillPending.length === 1) {
			setWarehouseId(stillPending[0].id);
		} else if (selectableWarehouses.length === 1) {
			setWarehouseId(selectableWarehouses[0].id);
		}
		// eslint-disable-next-line react-hooks/exhaustive-deps
	}, [isOpen, presetWarehouseId, selectableWarehouses, pendingWarehouseIds]);

	// Packing-list options for every still-un-tagged allocation at the chosen
	// warehouse — "since we track items with purchase inquiry, need to ask
	// which purchase inquiry items to be bar coded... warehouse keeper should
	// select which packing list he bar coding".
	const { data: packingOptions = [], isFetching: optionsLoading } = useQuery({
		queryKey: ['goodsTransferPackingLists', request?.id, warehouseId],
		queryFn: () => getPackingListOptionsApi(request!.id, Number(warehouseId)),
		enabled: isOpen && !!request && !!warehouseId,
	});

	// This warehouse's own draws, keyed by allocationId — pre-filled FIFO as
	// soon as options load, then fully editable (change a row's packing
	// list/qty, add another source, or remove one) before generating.
	const [draws, setDraws] = useState<Record<number, PackingListDraw[]>>({});

	useEffect(() => {
		setDraws({});
	}, [warehouseId]);

	useEffect(() => {
		if (packingOptions.length === 0) return;
		setDraws((prev) => {
			const next = { ...prev };
			let changed = false;
			packingOptions.forEach((line) => {
				if (!next[line.allocationId]) {
					next[line.allocationId] = defaultDraws(line.options, line.allocatedQty);
					changed = true;
				}
			});
			return changed ? next : prev;
		});
	}, [packingOptions]);

	const setLineDraws = (allocationId: number, rows: PackingListDraw[]) =>
		setDraws((prev) => ({ ...prev, [allocationId]: rows }));

	if (!request) return null;

	const presetWarehouseName = presetWarehouseId
		? warehouses.find((w) => w.id === presetWarehouseId)?.name
		: undefined;
	const selectedWarehouseName = warehouseId
		? warehouses.find((w) => w.id === Number(warehouseId))?.name ?? `Warehouse ${warehouseId}`
		: undefined;

	// Only this warehouse's own allocation per item — not the item's full
	// approved quantity, which may include other warehouses' slices.
	const pendingLines = warehouseId
		? request.items
				// One row per allocation, not per item: an item can carry more
				// than one allocation at the same warehouse (older approvals
				// allowed the same warehouse to be picked twice), and each
				// one needs its own tags.
				.flatMap((item) =>
					item.allocations
						.filter((a) => a.warehouseId === Number(warehouseId) && a.allocatedQty > 0)
						.map((allocation) => ({ item, allocation })),
				)
		: [];
	const generatableLines = pendingLines.filter((row) => row.allocation!.barcodeUnits.length === 0);

	// Every generatable line's own draws must add up exactly to its
	// allocatedQty before "Generate Barcodes" is allowed — mirrors the
	// backend's own check (GoodsTransferService#generateBarcodes), just
	// surfaced up front instead of as a rejected request.
	const allLinesReadyToGenerate =
		generatableLines.length > 0 &&
		generatableLines.every(({ allocation }) => {
			const rows = draws[allocation!.id] ?? [];
			return rows.length > 0 && drawsTotal(rows) === allocation!.allocatedQty;
		});

	// This warehouse's own tags only — never another warehouse's, even if
	// this same request has plenty already generated elsewhere.
	const warehouseUnits = pendingLines.flatMap(({ item, allocation }) =>
		allocation!.barcodeUnits.map((unit) => ({ item, unit })),
	);

	const openPrintSheet = () => {
		const renderBarcode = (code: string) => {
			try {
				return code128Svg(code, { barHeight: 50, fontSize: 12 });
			} catch {
				// A code with characters Code 128-B can't carry (never the case
				// for backend-generated tags) still prints its text, so the tag
				// can at least be typed in at the till.
				return `<div class="code-fallback">${escapeHtml(code)}</div>`;
			}
		};

		const labels = warehouseUnits
			.map(
				({ item, unit }) => `
				<div class="label">
					<div class="title">${escapeHtml(item.productName || 'Item')}</div>
					<div class="sub">${escapeHtml([item.size, item.color].filter(Boolean).join(' / ') || '—')}</div>
					<div class="bc">${renderBarcode(unit.barcode)}</div>
					<div class="sku">SKU: ${escapeHtml(item.sku)} · Unit ${unit.unitNo}</div>
				</div>`,
			)
			.join('');

		if (labels.length === 0) return;

		setPrinting(true);
		const win = window.open('', '_blank', 'width=900,height=700');
		if (!win) {
			setPrinting(false);
			return;
		}

		win.document.open();
		win.document.write(`<!doctype html>
<html>
<head>
<meta charset="utf-8" />
<title>Barcodes — ${escapeHtml(request.requestNo)} — ${escapeHtml(selectedWarehouseName ?? '')}</title>
<style>
	body { font-family: sans-serif; margin: 16px; }
	.sheet { display: flex; flex-wrap: wrap; gap: 12px; }
	.label {
		width: 260px;
		border: 1px solid #ccc;
		border-radius: 6px;
		padding: 8px;
		text-align: center;
		break-inside: avoid;
		page-break-inside: avoid;
	}
	.title { font-weight: 700; font-size: 13px; margin-bottom: 2px; }
	.sub { font-size: 11px; color: #666; margin-bottom: 6px; }
	.sku { font-size: 11px; color: #333; margin-top: 4px; }
	.bc svg { display: block; width: 100%; height: auto; }
	.code-fallback { font-family: monospace; font-size: 14px; padding: 12px 0; }
	@media print {
		.toolbar { display: none; }
		body { margin: 0; }
	}
</style>
</head>
<body>
	<div class="toolbar" style="margin-bottom:12px;">
		<button onclick="window.print()">Print</button>
	</div>
	<div class="sheet">${labels}</div>
</body>
</html>`);
		win.document.close();
		// Barcodes are already inline SVG, so nothing needs to load first — a
		// short delay just lets the new tab lay out before the print dialog.
		win.focus();
		setTimeout(() => win.print(), 300);
		setPrinting(false);
	};

	return (
		<Modal isOpen={isOpen} setIsOpen={setIsOpen} size='lg' isScrollable isCentered titleId='goodsTransferBarcodeModal'>
			<ModalHeader setIsOpen={setIsOpen}>
				<ModalTitle id='goodsTransferBarcodeModal'>
					Barcodes — {request.requestNo} ({request.showroomName})
				</ModalTitle>
			</ModalHeader>
			<ModalBody style={{ maxHeight: 'calc(100vh - 260px)', overflowY: 'auto' }}>
				<Alert color='info' isLight className='mb-3'>
					Generate barcodes once per warehouse — every unit allocated from that warehouse gets its own tag
					(e.g. 50 pcs from Warehouse 1 → 50 individual barcodes) so you can print and physically tag every
					item. Both generating and printing only ever cover your own assigned warehouse's slice — other
					warehouses on this request generate and print their own tags independently. Already-generated
					tags are never regenerated.
				</Alert>

				{!isSuperAdmin && warehouseIds.length > 0 && selectableWarehouses.length === 0 ? (
					<Alert color='warning' isLight>
						None of your assigned warehouses have anything allocated on this request.
					</Alert>
				) : presetWarehouseId ? (
					<FormGroup id='warehouseId' label='Warehouse'>
						<Input value={presetWarehouseName ?? `Warehouse ${presetWarehouseId}`} disabled />
					</FormGroup>
				) : (
					<FormGroup id='warehouseId' label='Warehouse'>
						<Select
							name='warehouseId'
							value={warehouseId}
							onChange={(e: React.ChangeEvent<HTMLSelectElement>) =>
								setWarehouseId(e.target.value ? Number(e.target.value) : '')
							}
							ariaLabel='Warehouse'>
							<option value=''>Select a warehouse...</option>
							{selectableWarehouses.map((w) => (
								<option key={w.id} value={w.id}>
									{w.name}
									{pendingWarehouseIds.has(w.id) ? '' : ' — tagged'}
								</option>
							))}
						</Select>
					</FormGroup>
				)}

				{generatableLines.length > 0 && warehouseId && (
					<Alert color='info' isLight className='mb-3'>
						Pre-filled oldest-first ("first come, first go") from what's available — pick a different
						packing list, split across more than one, or leave it as-is. Every line below must add up to
						its own Qty before you can generate.
					</Alert>
				)}

				<table className='table table-sm table-bordered align-middle mt-3'>
					<thead className='table-light'>
						<tr>
							<th>Item</th>
							<th>SKU</th>
							<th style={{ width: 90 }}>Qty</th>
							<th style={{ minWidth: 260 }}>Tags / Packing list</th>
						</tr>
					</thead>
					<tbody>
						{pendingLines.length === 0 ? (
							<tr>
								<td colSpan={4} className='text-center text-muted small py-3'>
									{warehouseId
										? 'Nothing allocated to this warehouse on this request.'
										: 'Pick a warehouse to see its items.'}
								</td>
							</tr>
						) : (
							pendingLines.map(({ item, allocation }) => {
								const line = packingOptions.find((p) => p.allocationId === allocation!.id);
								const rows = draws[allocation!.id] ?? [];
								const assigned = drawsTotal(rows);
								const needed = allocation!.allocatedQty;
								const isValid = rows.length > 0 && assigned === needed;

								return (
									<tr key={allocation!.id}>
										<td>
											{item.productName || '—'}
											{(item.size || item.color) && (
												<div className='small text-muted'>
													{[item.size, item.color].filter(Boolean).join(' / ')}
												</div>
											)}
										</td>
										<td>{item.sku}</td>
										<td>{allocation?.allocatedQty}</td>
										<td>
											{allocation && allocation.barcodeUnits.length > 0 ? (
												<Badge color='success' isLight>
													{allocation.barcodeUnits.length} tag
													{allocation.barcodeUnits.length === 1 ? '' : 's'} generated
												</Badge>
											) : optionsLoading && !line ? (
												<span className='text-muted small'>
													<Spinner isSmall className='me-1' /> Loading packing lists...
												</span>
											) : (
												<div>
													{rows.map((row, idx) => (
														<div key={idx} className='d-flex align-items-center gap-1 mb-1'>
															<Select
																size='sm'
																ariaLabel='Packing list'
																value={row.batchId ?? '__none__'}
																onChange={(e: React.ChangeEvent<HTMLSelectElement>) => {
																	const v = e.target.value;
																	const next = [...rows];
																	next[idx] = { ...row, batchId: v === '__none__' ? null : Number(v) };
																	setLineDraws(allocation!.id, next);
																}}>
																{(line?.options ?? []).map((opt) => (
																	<option key={opt.batchId} value={opt.batchId}>
																		{opt.packingRefNo ?? opt.shipmentNo}
																		{opt.sourceInquiryNo ? ` · ${opt.sourceInquiryNo}` : ''} ·{' '}
																		{opt.remainingQty} left
																	</option>
																))}
																<option value='__none__'>No packing list (unknown source)</option>
															</Select>
															<Input
																type='number'
																size='sm'
																style={{ width: 70 }}
																value={row.qty}
																min={0}
																onChange={(e: React.ChangeEvent<HTMLInputElement>) => {
																	const next = [...rows];
																	next[idx] = { ...row, qty: Number(e.target.value) || 0 };
																	setLineDraws(allocation!.id, next);
																}}
															/>
															{rows.length > 1 && (
																<Button
																	size='sm'
																	color='light'
																	icon='Delete'
																	onClick={() => setLineDraws(allocation!.id, rows.filter((_, i) => i !== idx))}
																/>
															)}
														</div>
													))}
													<div className='d-flex align-items-center justify-content-between'>
														<Button
															size='sm'
															color='light'
															isLight
															icon='Add'
															onClick={() =>
																setLineDraws(allocation!.id, [
																	...rows,
																	{ batchId: line?.options?.[0]?.batchId ?? null, qty: 0 },
																])
															}>
															Add source
														</Button>
														<span className={`small ${isValid ? 'text-success' : 'text-danger'}`}>
															Assigned {assigned} / {needed}
														</span>
													</div>
												</div>
											)}
										</td>
									</tr>
								);
							})
						)}
					</tbody>
				</table>
			</ModalBody>
			<ModalFooter>
				<Button color='light' onClick={() => setIsOpen(false)}>
					Close
				</Button>
				{generatableLines.length > 0 && (
					<Button
						color='primary'
						isLight
						icon='QrCode'
						isDisable={isLoading || !warehouseId || !allLinesReadyToGenerate}
						onClick={() => {
							if (!warehouseId || !allLinesReadyToGenerate) return;
							const allocations: GoodsTransferAllocationDraws[] = generatableLines.map(({ allocation }) => ({
								allocationId: allocation!.id,
								draws: (draws[allocation!.id] ?? []).filter((d) => d.qty > 0),
							}));
							onGenerate(request.id, Number(warehouseId), allocations);
						}}>
						{isLoading
							? 'Generating...'
							: allLinesReadyToGenerate
								? 'Generate Barcodes'
								: 'Assign packing lists to continue'}
					</Button>
				)}
				{warehouseUnits.length > 0 && (
					<Button color='success' isLight icon='Print' isDisable={printing} onClick={openPrintSheet}>
						{printing
							? 'Preparing...'
							: `Print ${warehouseUnits.length} Barcode${warehouseUnits.length === 1 ? '' : 's'} — ${selectedWarehouseName}`}
					</Button>
				)}
			</ModalFooter>
		</Modal>
	);
};

export default GoodsTransferBarcodeModal;
