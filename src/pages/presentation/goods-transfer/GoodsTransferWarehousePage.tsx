import React, { useEffect, useState } from 'react';
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import { useSearchParams } from 'react-router-dom';
import PageWrapper from '../../../layout/PageWrapper/PageWrapper';
import SubHeader, {
	SubHeaderLeft,
	SubHeaderRight,
	SubheaderSeparator,
} from '../../../layout/SubHeader/SubHeader';
import Page from '../../../layout/Page/Page';
import Card, { CardBody } from '../../../components/bootstrap/Card';
import Icon from '../../../components/icon/Icon';
import Badge from '../../../components/bootstrap/Badge';
import Button from '../../../components/bootstrap/Button';
import DataTable, { DataTableColumn } from '../../../components/common/DataTable/DataTable';
import DataTableActionMenu from '../../../components/common/DataTable/DataTableActionMenu';
import { PERMISSIONS } from '../../../constants/permissions';
import { usePermission } from '../../../hooks/usePermission';
import showNotification from '../../../components/extras/showNotification';
import { getApiErrorMessage } from '../../../utils/apiError';
import { getWarehousesApi } from '../../../api/warehouses.api';
import {
	getGoodsTransfersApi,
	generateGoodsTransferBarcodesApi,
	issueGoodsTransferApi,
	GoodsTransferRequest,
	GoodsTransferAllocationDraws,
	GOODS_TRANSFER_STATUS_ORDER,
} from '../../../api/goodsTransfer.api';
import GoodsTransferBarcodeModal from './GoodsTransferBarcodeModal';
import GoodsTransferDetailDrawer from './GoodsTransferDetailDrawer';
import GoodsTransferIssueModal from './GoodsTransferIssueModal';
import GoodsTransferStatusBadge from './goodsTransferStatus';
import LocationTabs from './LocationTabs';

// This warehouse still has an allocation that hasn't had its own barcode
// tags generated yet — "specific barcodes can be generated by warehouse
// assigned user" means each warehouse's own queue only shows its own
// un-generated slice, not the whole request.
const hasBarcodePendingAt = (row: GoodsTransferRequest, warehouseId: number) =>
	row.items.some((item) =>
		item.allocations.some((a) => a.warehouseId === warehouseId && a.allocatedQty > 0 && a.barcodeUnits.length === 0),
	);

// This warehouse's own slice is tagged and still has something left to
// issue — barcoding must come before issuing for that same slice.
const hasIssuePendingAt = (row: GoodsTransferRequest, warehouseId: number) =>
	row.items.some((item) =>
		item.allocations.some(
			(a) => a.warehouseId === warehouseId && a.issuedQty < a.allocatedQty && a.barcodeUnits.length > 0,
		),
	);

// This warehouse had any allocation at all on this request — used for the
// History tab, where nothing is "pending" any more so scoping is just "was
// this warehouse's own slice part of it".
const wasInvolvedAt = (row: GoodsTransferRequest, warehouseId: number) =>
	row.items.some((item) => item.allocations.some((a) => a.warehouseId === warehouseId && a.allocatedQty > 0));

// This page's own active-queue statuses — everything past PARTIALLY_ISSUED
// (i.e. ISSUED / RECEIVED) belongs in History instead.
const RELEVANT_STATUSES = new Set<GoodsTransferRequest['status']>([
	'APPROVED',
	'PARTIALLY_BARCODED',
	'BARCODED',
	'PARTIALLY_ISSUED',
]);
const MAX_RELEVANT_INDEX = Math.max(
	...Array.from(RELEVANT_STATUSES).map((s) => GOODS_TRANSFER_STATUS_ORDER.indexOf(s)),
);

/**
 * Steps 3 & 4 for the store keeper — "store keeper got the item list, he
 * generates bar code for requested items... and issue items to Showroom".
 * One queue covering APPROVED (needs barcodes), PARTIALLY_BARCODED, BARCODED
 * and PARTIALLY_ISSUED (ready to issue, or still waiting on another
 * warehouse's slice) requests. Tabs mirror the Bay-1 receiving pattern: only
 * warehouses a store keeper is assigned to are switchable, and each specific
 * tab pre-selects (and locks) that warehouse in both the Barcode and Issue
 * modals so they only ever act on their own slice — "specific barcodes can
 * be generated by warehouse assigned user... only 50 barcodes can be created
 * by warehouse 1 assigned user" when a 100-unit line is split 50/50 across
 * two warehouses, and the same independence applies to issuing.
 * <p>
 * An Active/History button-group (mirrors ImportReceivingPage /
 * ImportGrnPage) separates that live queue from everything already fully
 * issued or received, scoped to the selected warehouse the same way the
 * active queue is.
 */
const GoodsTransferWarehousePage = () => {
	const queryClient = useQueryClient();
	const { hasPermission } = usePermission();
	const [searchParams, setSearchParams] = useSearchParams();
	const [barcodeTarget, setBarcodeTarget] = useState<GoodsTransferRequest | null>(null);
	const [isBarcodeOpen, setIsBarcodeOpen] = useState(false);
	const [issueTarget, setIssueTarget] = useState<GoodsTransferRequest | null>(null);
	const [isIssueOpen, setIsIssueOpen] = useState(false);
	const [selectedWarehouse, setSelectedWarehouse] = useState<number | 'ALL'>('ALL');
	const [viewTarget, setViewTarget] = useState<GoodsTransferRequest | null>(null);
	const [isViewOpen, setIsViewOpen] = useState(false);
	const [tab, setTab] = useState<'active' | 'history'>('active');

	const canGenerate = hasPermission(PERMISSIONS.GENERATE_GOODS_TRANSFER_BARCODES);
	const canIssue = hasPermission(PERMISSIONS.ISSUE_GOODS_TRANSFER);

	const { data: warehouses = [] } = useQuery({ queryKey: ['warehouses'], queryFn: getWarehousesApi });

	const { data: allRequests = [], isLoading, error } = useQuery({
		queryKey: ['goodsTransfers'],
		queryFn: getGoodsTransfersApi,
	});

	// Deep-link support for "go to view" notifications: NotificationBell
	// routes here with ?open=<requestId>, so once the list has loaded, find
	// that row (regardless of which Active/History tab it currently falls
	// under) and open its detail drawer, then strip the param so a
	// back/refresh doesn't re-trigger it.
	useEffect(() => {
		const openId = searchParams.get('open');
		if (!openId || allRequests.length === 0) return;
		const row = allRequests.find((r) => r.id === Number(openId));
		if (row) {
			setViewTarget(row);
			setIsViewOpen(true);
		}
		setSearchParams(
			(prev) => {
				prev.delete('open');
				return prev;
			},
			{ replace: true },
		);
		// eslint-disable-next-line react-hooks/exhaustive-deps
	}, [searchParams, allRequests]);

	const allActive = allRequests.filter((r) => RELEVANT_STATUSES.has(r.status));
	// Everything that's moved past this page's own step — ISSUED / RECEIVED.
	// REQUESTED (index 0, not yet reached this page) and REJECTED (index -1,
	// never reaches this page at all) both fall below MAX_RELEVANT_INDEX too,
	// so neither one leaks into this page's History by accident.
	const allHistory = allRequests.filter((r) => GOODS_TRANSFER_STATUS_ORDER.indexOf(r.status) > MAX_RELEVANT_INDEX);

	// A row belongs on this warehouse's own Active tab if it still has either
	// barcoding or issuing left to do at that warehouse specifically — a
	// request sitting at PARTIALLY_BARCODED can simultaneously be "still
	// needs barcodes" for one warehouse and "ready to issue" for another.
	// Nothing is pending any more in History, so that tab just scopes to
	// "was this warehouse's own slice part of it".
	const active =
		selectedWarehouse === 'ALL'
			? allActive
			: allActive.filter(
					(row) => hasBarcodePendingAt(row, selectedWarehouse) || hasIssuePendingAt(row, selectedWarehouse),
				);
	const history =
		selectedWarehouse === 'ALL'
			? allHistory
			: allHistory.filter((row) => wasInvolvedAt(row, selectedWarehouse));

	const queue = tab === 'active' ? active : history;

	const invalidate = () => queryClient.invalidateQueries({ queryKey: ['goodsTransfers'] });

	const generateMutation = useMutation({
		mutationFn: ({
			id,
			warehouseId,
			allocations,
		}: {
			id: number;
			warehouseId: number;
			allocations: GoodsTransferAllocationDraws[];
		}) => generateGoodsTransferBarcodesApi(id, warehouseId, allocations),
		onSuccess: (updated) => {
			invalidate();
			setBarcodeTarget(updated);
			showNotification(
				<>
					<Icon icon='QrCode' className='me-2' />
					Barcodes Generated
				</>,
				updated.status === 'BARCODED'
					? `${updated.requestNo} is fully tagged and ready to issue.`
					: `${updated.requestNo} — your portion is tagged; waiting on the remaining warehouse(s).`,
				'success',
			);
		},
		onError: (e) => showNotification('Error', getApiErrorMessage(e, 'Failed to generate barcodes'), 'danger'),
	});

	const issueMutation = useMutation({
		mutationFn: ({ id, warehouseId }: { id: number; warehouseId: number }) =>
			issueGoodsTransferApi(id, warehouseId),
		onSuccess: (updated) => {
			invalidate();
			setIsIssueOpen(false);
			setIssueTarget(null);
			showNotification(
				<>
					<Icon icon='LocalShipping' className='me-2' />
					{updated.status === 'ISSUED' ? 'Items Issued' : 'Partial Issue Recorded'}
				</>,
				updated.status === 'ISSUED'
					? `${updated.requestNo} has been fully issued to ${updated.showroomName}.`
					: `${updated.requestNo} — your portion has been issued; waiting on the remaining warehouse(s).`,
				'success',
			);
		},
		onError: (e) => showNotification('Error', getApiErrorMessage(e, 'Failed to issue items'), 'danger'),
	});

	const columns: DataTableColumn<GoodsTransferRequest>[] = [
		{
			key: 'requestNo',
			label: 'Request No',
			render: (row) => <span className='fw-bold text-primary'>{row.requestNo}</span>,
		},
		{ key: 'showroomName', label: 'Showroom' },
		{
			key: 'items',
			label: 'Items',
			align: 'center',
			render: (row) => <Badge color='secondary' isLight>{row.items.length}</Badge>,
			sortValue: (row) => row.items.length,
		},
		{
			key: 'status',
			label: 'Status',
			render: (row) => <GoodsTransferStatusBadge status={row.status} />,
		},
		{
			key: 'approvedAt',
			label: 'Approved At',
			render: (row) => (row.approvedAt ? new Date(row.approvedAt).toLocaleString() : '—'),
			sortValue: (row) => (row.approvedAt ? new Date(row.approvedAt).getTime() : 0),
		},
		{
			key: 'actions',
			label: '',
			align: 'right' as any,
			sortable: false,
			searchable: false,
			render: (row) => (
				<DataTableActionMenu
					actions={[
						{
							key: 'view',
							label: 'View Details',
							icon: 'ti ti-eye',
							className: 'text-info',
							onClick: () => {
								setViewTarget(row);
								setIsViewOpen(true);
							},
						},
						...(canGenerate && (row.status === 'APPROVED' || row.status === 'PARTIALLY_BARCODED')
							? [
									{
										key: 'barcodes',
										label: 'Generate Barcodes',
										icon: 'ti ti-barcode',
										onClick: () => {
											setBarcodeTarget(row);
											setIsBarcodeOpen(true);
										},
									},
								]
							: canGenerate
								? [
										{
											key: 'barcodes',
											label: 'View / Print Barcodes',
											icon: 'ti ti-barcode',
											onClick: () => {
												setBarcodeTarget(row);
												setIsBarcodeOpen(true);
											},
										},
									]
								: []),
						...(canIssue &&
						(row.status === 'PARTIALLY_BARCODED' || row.status === 'BARCODED' || row.status === 'PARTIALLY_ISSUED')
							? [
									{
										key: 'issue',
										label: 'Issue to Showroom',
										icon: 'ti ti-truck-delivery',
										className: 'text-success',
										onClick: () => {
											setIssueTarget(row);
											setIsIssueOpen(true);
										},
									},
								]
							: []),
					]}
				/>
			),
		},
	];

	return (
		<PageWrapper
			title='Barcode & Issue'
			requiredPermission={[PERMISSIONS.GENERATE_GOODS_TRANSFER_BARCODES, PERMISSIONS.ISSUE_GOODS_TRANSFER]}>
			<SubHeader>
				<SubHeaderLeft>
					<Icon icon='QrCode' size='2x' color='primary' />
					<span className='fs-5 fw-bold ms-2'>Barcode &amp; Issue Queue</span>
					<SubheaderSeparator />
					<span className='text-muted'>
						{isLoading
							? 'Loading…'
							: tab === 'active'
								? `${active.length} request(s) in progress`
								: `${history.length} in history`}
					</span>
				</SubHeaderLeft>
				<SubHeaderRight />
			</SubHeader>

			<Page>
				<div className='row h-100'>
					<div className='col-12'>
						<LocationTabs
							locations={warehouses}
							selectedId={selectedWarehouse}
							onSelect={setSelectedWarehouse}
						/>
						<Card stretch>
							<CardBody style={{ overflow: 'visible' }}>
								<div className='btn-group mb-3' role='group' aria-label='View'>
									<Button
										size='sm'
										color={tab === 'active' ? 'primary' : 'light'}
										isLight={tab !== 'active'}
										onClick={() => setTab('active')}>
										Active ({active.length})
									</Button>
									<Button
										size='sm'
										color={tab === 'history' ? 'primary' : 'light'}
										isLight={tab !== 'history'}
										onClick={() => setTab('history')}>
										History ({history.length})
									</Button>
								</div>
								<DataTable
									columns={columns}
									data={queue}
									rowKey='id'
									loading={isLoading}
									error={error}
									fileName={tab === 'active' ? 'goods-transfer-warehouse-queue' : 'goods-transfer-warehouse-history'}
									emptyText={
										tab === 'active'
											? 'Nothing waiting — approved requests will show up here.'
											: 'Nothing in history yet.'
									}
									showActions={false}
								/>
							</CardBody>
						</Card>
					</div>
				</div>
			</Page>

			<GoodsTransferBarcodeModal
				isOpen={isBarcodeOpen}
				setIsOpen={(v) => {
					setIsBarcodeOpen(v);
					if (!v) setBarcodeTarget(null);
				}}
				request={barcodeTarget}
				isLoading={generateMutation.isPending}
				presetWarehouseId={selectedWarehouse === 'ALL' ? null : selectedWarehouse}
				onGenerate={(id, warehouseId, allocations) => generateMutation.mutate({ id, warehouseId, allocations })}
			/>

			<GoodsTransferIssueModal
				isOpen={isIssueOpen}
				setIsOpen={(v) => {
					setIsIssueOpen(v);
					if (!v) setIssueTarget(null);
				}}
				request={issueTarget}
				isLoading={issueMutation.isPending}
				presetWarehouseId={selectedWarehouse === 'ALL' ? null : selectedWarehouse}
				onIssue={(id, warehouseId) => issueMutation.mutate({ id, warehouseId })}
			/>

			<GoodsTransferDetailDrawer isOpen={isViewOpen} setIsOpen={setIsViewOpen} request={viewTarget} />
		</PageWrapper>
	);
};

export default GoodsTransferWarehousePage;
